def add(*rows):
    z=[F(0)]*max(map(len,rows))
    for row in rows:
        for j,v in enumerate(row):z[j]+=v
    return z
def scale(c,row):return [c*x for x in row]
def polys(d,N):
    P=[[F(1)],[F(0),F(1)]]
    for k in range(1,N):
        P.append(add(scale(F(2*k+d-2,k+d-2),[0]+P[-1]),scale(-F(k,k+d-2),P[-2])))
    return P
def bers(a):
    n=len(a)-1
    # t=-1+3u/2, u in [0,1]
    b=[sum(a[j]*comb(j,i)*(-1)**(j-i) for j in range(i,n+1))*F(3,2)**i for i in range(n+1)]
    out=[sum(F(comb(i,j),comb(n,j))*b[j] for j in range(i+1))for i in range(n+1)]
    d=lcm(*(x.denominator for x in out));return [int(x*d) for x in out]
def proof(a,dep=0):
    if max(a)<=0:return 1
    assert dep<35 and a[0]<=0 and a[-1]<=0,'nonnegative endpoint or depth'
    n=len(a)-1
    lo=[];hi=[];r=a
    for j in range(n+1):
        lo.append(r[0]<<(n-j));hi.append(r[-1]<<(n-j))
        r=[v+w for v,w in zip(r,r[1:])]
    return proof(lo,dep+1)+proof(hi[::-1],dep+1)
