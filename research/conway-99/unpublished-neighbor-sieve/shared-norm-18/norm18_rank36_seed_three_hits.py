from original_site_populations import calc
def check():
    o,w,c,g,u,ub,red=calc(36,[],export=True)
    N=2402*u[0,18]
    Y1=c((0,14));Y2=c((0,28))+2*c((3,39));M0=c((2,22))
    Ct=lambda t:9*Y2+18*Y1-(369+10*t)*M0+(5*t*t-4158)*o
    pos={**ub,'Ct34':Ct(34),'Ct48':Ct(48),
        'cap121':29372*o-g((1,21)),'sq':5544*o+2402*(3*u[1,27]-2*u[2,26]-3*u[0,16]),
        'root':-1*g((0,14)),'444':w((4,44))}
    tests=[
        (14275638990,441845165853000,{16:64475936201160,127:220867430940,337:3525883189500,
            228:4895973732960,230:963240576120},
        {('u',(1,21)):6518075390820,('u',(2,26)):14246009934120,'mark((2, 36), -2)':50946030100,
         'mark((3, 53), 1)':343837410,'mark((3, 53), -2)':769929405,
         "nonneg('W', (-4, 44, 2))":14474832032430,"nonneg('W', (-3, 33, 0))":2546542788030,
         "nonneg('W', (-3, 35, 1))":6498915897870,"nonneg('C', (-4, 46, -1))":6140417775030,
         "nonneg('C', (0, 14, -1))":156519732004020,'root':83730972780,'444':3687669130860,
         'Ct34':4388009094,'Ct48':2995494656}),
        (13090,404031180,{26:2858380,226:17150280,127:2858380},
        {('u',(0,20)):2858380,('u',(2,28)):4287570,('u',(0,24)):1429190,('u',(0,16)):8575140,
         "nonneg('W', (-3, 33, 0))":8575140,"nonneg('W', (-3, 35, 1))":4161465,
         "nonneg('W', (-2, 22, 0))":11025180,"nonneg('W', (-1, 23, -1))":70744905,
         "nonneg('W', (0, 14, 0))":30794841,'cap121':19040,'444':1429190}),
        (16898,585281984,{26:3430056,127:31442180,230:1143352},
        {('u',(0,16)):42875700,('u',(2,28)):6002598,('u',(0,24)):1429190,
         "nonneg('W', (-3, 33, 0))":10290168,"nonneg('W', (-3, 35, 1))":5826051,
         "nonneg('W', (-2, 22, 0))":11025180,"nonneg('W', (-1, 23, -1))":99042867,
         "nonneg('W', (0, 14, 0))":42446943,'sq':3808,'cap121':24276,'444':3144218})]
    lows=[]
    for b,t,missing,plus in tests:
        z=b*N-t*o
        for k,h in missing.items():
            assert h>0;z+=h*u[divmod(k,100)]
        for k,h in plus.items():
            assert h>0;z-=h*pos[k]
        assert not any(red(z))
        lows.append(2*((t+2*b-1)//(2*b)))
    assert lows==[30952,30866,34638]
    print('Three rank-36 same-N18 floors',lows,'versus 29842.')
if __name__=='__main__':check()
