"""Exact PG(2,3) perfect-matching orbits for new Hamiltonian-trade discovery.
This is symmetry reduction for an actual binary search, not a Ryser solution.
"""
from itertools import product
from pathlib import Path
import json
from ryser_baseline_verify import projective_vectors, matching_dp

def normalize(v):
    a=next(x for x in v if x)
    return tuple((x*(1 if a==1 else 2))%3 for x in v)

def inverse(a):
    z=[list(a[i])+[int(i==j) for j in range(3)] for i in range(3)]
    for col in range(3):
        pivot=next((r for r in range(col,3) if z[r][col]),None)
        if pivot is None:return None
        z[col],z[pivot]=z[pivot],z[col]
        inv=1 if z[col][col]==1 else 2
        z[col]=[x*inv%3 for x in z[col]]
        for r in range(3):
            if r!=col:
                b=z[r][col]
                z[r]=[(x-b*y)%3 for x,y in zip(z[r],z[col])]
    return tuple(tuple(row[3:]) for row in z)

def multiply(a,v):return tuple(sum(x*y for x,y in zip(row,v))%3 for row in a)

def main():
    points=projective_vectors();index={v:i for i,v in enumerate(points)};n=13
    rows=[sum(1<<j for j,p in enumerate(points) if sum(x*y for x,y in zip(l,p))%3==0) for l in points]
    matchings=set()
    def dfs(i,used,m):
        if i==n:matchings.add(tuple(m));return
        bs=rows[i]&~used
        while bs:
            bit=bs&-bs;bs-=bit;j=bit.bit_length()-1
            dfs(i+1,used|bit,m+[j])
    dfs(0,0,[])
    if len(matchings)!=3852:raise RuntimeError('matching count differs from both exact baseline algorithms')
    actions=[]
    for flat in product(range(3),repeat=9):
        if not any(flat) or next(x for x in flat if x)!=1:continue
        a=tuple(tuple(flat[3*i:3*i+3]) for i in range(3));inv=inverse(a)
        if inv is None:continue
        dual=tuple(tuple(inv[j][i] for j in range(3)) for i in range(3))
        col=tuple(index[normalize(multiply(a,v))] for v in points)
        row=tuple(index[normalize(multiply(dual,v))] for v in points)
        if any(bool(rows[i]>>j&1)!=bool(rows[row[i]]>>col[j]&1) for i in range(n) for j in range(n)):
            raise RuntimeError('claimed group action does not preserve actual incidence')
        actions.append((row,col))
    if len(actions)!=5616:raise RuntimeError('wrong PGL(3,3) size')
    unseen=matchings.copy();reps=[]
    while unseen:
        m=min(unseen);orbit=set()
        for row,col in actions:
            image=[0]*n
            for i,j in enumerate(m):image[row[i]]=col[j]
            orbit.add(tuple(image))
        if not orbit<=unseen:raise RuntimeError('orbits overlap or image leaves matching set')
        unseen-=orbit
        diag=[sum(1<<j for j in range(n) if rows[i]>>m[j]&1) for i in range(n)]
        core=[r^(1<<i) for i,r in enumerate(diag)]
        cp=matching_dp(core,n)
        reps.append({'original_matching':m,'orbit_size':len(orbit),'diagonal_labeled_plane_rows':diag,'removed_matching_core_permanent':cp})
    reps.sort(key=lambda r:(r['removed_matching_core_permanent'],r['original_matching']))
    out={'scope':'Exact symmetry reduction only for bounded Hamiltonian trade discovery; no complete Ryser result.','n':13,'k':4,'actual_PGL_action_size':len(actions),'all_incidence_matchings_count':len(matchings),'orbits_count':len(reps),'representatives':reps}
    base=Path(__file__).parent
    (base/'ryser-matching-orbits.json').write_text(json.dumps(out,indent=2)+'\n')
    arrays=',\n'.join('M{'+','.join(map(str,r['diagonal_labeled_plane_rows']))+'}' for r in reps)
    (base/'ryser_hamiltonian_representatives.hpp').write_text('// Generated by exact incidence-preserving PGL(3,3) orbit computation.\nconst std::vector<M> representatives = {\n'+arrays+'\n};\n')
    print({key:val for key,val in out.items() if key!='representatives'})
    print([(r['orbit_size'],r['removed_matching_core_permanent']) for r in reps])
if __name__=='__main__':main()
