#!/usr/bin/env python3
"""Build whitelisted, deterministic archive and complete readable source patch."""
from __future__ import annotations
import argparse,gzip,hashlib,io,json,tarfile
from pathlib import Path
ROOT=Path(__file__).resolve().parent
PREFIX='notes/conserved-quadratic-fluctuations'; EPOCH=1791331200

def require(ok,message):
    if not ok: raise RuntimeError(message)

def files():
    names=json.loads((ROOT/'PUBLIC_FILES.json').read_text())['files']
    require(len(names)==len(set(names)),'Duplicate publication-whitelist path.')
    for name in names:
        p=Path(name); require(not p.is_absolute() and '..' not in p.parts and p.as_posix()==name,'Unsafe whitelist path.')
    require('package-manifest.json' not in names,'Manifest is self-excluded.')
    actual=[]
    for p in ROOT.rglob('*'):
        require(not p.is_symlink(),'Symlinks are excluded from the public release.')
        if p.is_file() and '__pycache__' not in p.relative_to(ROOT).parts and p.suffix!='.pyc': actual.append(p.relative_to(ROOT).as_posix())
    require(set(actual)-{'package-manifest.json'}==set(names),'Stage does not match whitelist: '+str(sorted((set(actual)-{'package-manifest.json'})^set(names))))
    return sorted(names)

def archive_bytes(names):
    raw=io.BytesIO()
    with tarfile.open(fileobj=raw,mode='w',format=tarfile.PAX_FORMAT) as archive:
        for name in names:
            data=(ROOT/name).read_bytes();info=tarfile.TarInfo(PREFIX+'/'+name);info.size=len(data);info.mtime=EPOCH;info.mode=0o644;info.uid=info.gid=0;info.uname=info.gname='';archive.addfile(info,io.BytesIO(data))
    compressed=io.BytesIO()
    with gzip.GzipFile(filename='',mode='wb',fileobj=compressed,mtime=0,compresslevel=9) as output: output.write(raw.getvalue())
    return compressed.getvalue()

def patch_bytes(names):
    parts=[]
    for name in names:
        data=(ROOT/name).read_bytes()
        try: t=data.decode('utf-8')
        except UnicodeDecodeError: continue
        path=PREFIX+'/'+name;blob=hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest();lines=t.split('\n')
        if t.endswith('\n'): lines.pop()
        parts += [f'diff --git a/{path} b/{path}\n','new file mode 100644\n',f'index 0000000..{blob}\n','--- /dev/null\n',f'+++ b/{path}\n',f'@@ -0,0 +1,{len(lines)} @@\n'];parts.extend('+'+line+'\n' for line in lines)
        if not t.endswith('\n'): parts.append('\\ No newline at end of file\n')
    return ''.join(parts).encode()

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('output_directory',type=Path);args=parser.parse_args();out=args.output_directory.resolve()
    require(out!=ROOT and ROOT not in out.parents,'Delivery outputs must be outside the package.')
    names=files();rows=[]
    for name in names:
        data=(ROOT/name).read_bytes();rows.append({'path':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
    manifest={'format_version':2,'generated_utc':'2026-10-07T00:00:00Z','publication_whitelist':'PUBLIC_FILES.json','excluded':['package-manifest.json (self)','Python __pycache__ and *.pyc'],'files':rows}
    (ROOT/'package-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');names=sorted(names+['package-manifest.json']);archive=archive_bytes(names)
    require(archive==archive_bytes(names),'Repeated deterministic archive differs.')
    outputs=[('conserved-quadratic-fluctuations-v1.tar.gz',archive),('conserved-quadratic-fluctuations-v1.patch.txt',patch_bytes(names)),('conserved-quadratic-fluctuations-v1.pdf',(ROOT/'manuscript.pdf').read_bytes())]
    out.mkdir(parents=True,exist_ok=True);report=[]
    for name,data in outputs:
        (out/name).write_bytes(data);report.append({'name':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
    result={'packaged_files':len(names),'archive_repeat_identical':True,'outputs':report,'patch_scope':'all UTF-8 whitelisted files; binary PDF regenerated by build.py'}
    (out/'delivery-manifest.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result,indent=2))
if __name__=='__main__': main()
