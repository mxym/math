#!/usr/bin/env python3
"""Replay supplied and independent regressions and rebuild the sharp proof offline."""
from pathlib import Path
import hashlib
import json
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent

def require(ok, message):
    if not ok:
        raise RuntimeError(message)

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def run(cmd, cwd):
    p = subprocess.run(cmd, cwd=cwd, text=True, stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, check=False)
    require(p.returncode == 0, 'Command failed: '+repr(cmd)+'\n'+p.stdout)
    return p.stdout

def replay(name, source, certificate=None, expected_certificate=None):
    target = ROOT/'build/replay'/name
    target.mkdir(parents=True, exist_ok=True)
    script = target/source.name
    shutil.copyfile(source, script)
    normal = run([sys.executable, script.name], target)
    first = (target/certificate).read_bytes() if certificate else None
    optimized = run([sys.executable, '-O', script.name], target)
    require(normal == optimized, 'Normal/-O logs differ: '+name)
    if certificate:
        require((target/certificate).read_bytes() == first, 'Normal/-O certificates differ: '+name)
        require(hashlib.sha256(first).hexdigest() == expected_certificate,
                'Certificate changed from the exact pin: '+name)
    for mode, text in [('normal',normal),('optimized',optimized)]:
        (ROOT/'results'/(name+'.'+mode+'.log')).write_text(text, encoding='utf8')
    return {'normal_and_optimized_identical':True,
            'certificate_sha256':expected_certificate,
            'log_sha256':hashlib.sha256(normal.encode()).hexdigest()}

def main():
    (ROOT/'results').mkdir(exist_ok=True)
    provenance = json.loads((ROOT/'PROVENANCE.json').read_text())
    for f in provenance['source_files']:
        require(sha(ROOT/f['path']) == f['sha256'], 'Pinned source mismatch: '+f['path'])
        require((ROOT/f['path']).stat().st_size == f['bytes'], 'Pinned source size mismatch: '+f['path'])
    require(sha(ROOT/'check_exact.py') == '1a627f4a33aee55c1eac844868669fdaeb68f833ce22faccf5f3027fe6704b72','Supplied checker changed')
    require(sha(ROOT/'independent_checks.py') == '7894912020935c7b7dc64caf1292d8edfc8d0f00f4330b3310e7afde0c8f1117','Independent checker changed')
    require(sha(ROOT/'check_prior_independent.py') == '1d0c264f8a60dbfe221f0decc88d516fc66b4f30cddb0887de254444101fb630','Prior independent checker changed')
    checks = {
      'supplied': replay('supplied', ROOT/'check_exact.py','check_results.json','cac4575e072bc9be04ed45c44f928e44711a5bd45dec86c9186611562c7e613f'),
      'independent': replay('independent', ROOT/'independent_checks.py','independent_certificate.json','bf32f40af6ea1467723d90e12777df143beb0657954fd37af233796a5887d4a0'),
      'prior_independent': replay('prior_independent', ROOT/'check_prior_independent.py'),
      'truncation': replay('truncation',ROOT/'sources/truncation/check_exact.py','exact_certificate.json','fbfb6ee471650adc87b9e110f6cd12bcb6a376d3df7188130fb89723b0541196')}
    require(sha(ROOT/'check_results.json') == checks['supplied']['certificate_sha256'],'Published supplied certificate changed')
    require(sha(ROOT/'independent_certificate.json') == checks['independent']['certificate_sha256'],'Published independent certificate changed')
    run(['sh','build.sh'],ROOT)
    pdf_first, text_first = sha(ROOT/'proof.pdf'), sha(ROOT/'proof.txt')
    run(['sh','build.sh'],ROOT)
    require(sha(ROOT/'proof.pdf') == pdf_first and sha(ROOT/'proof.txt') == text_first,
            'Repeated PDF/text build was not deterministic')
    # The page-count comment is generated by pdfTeX, independently of text extraction.
    log=(ROOT/'build/typeset/pass2.log').read_text()
    require('Output written on proof.pdf (8 pages,' in log,'Expected an eight-page proof')
    require('Overfull' not in log and 'undefined references' not in log and 'undefined on input' not in log,'Typesetting warning')
    report={'status':'PASS','scope':'Reproducible finite arithmetic evidence and PDF build; analytic model audit is separate. Not human peer review or proof-assistant formalization.',
      'checks':checks,'pdf_pages':8,'deterministic_pdf_and_text':True,'pdf_shell_escape':False,
      'pinned_sources_verified':len(provenance['source_files']),
      'supplied_counts':json.loads((ROOT/'check_results.json').read_text())['counts'],
      'independent_counts':json.loads((ROOT/'independent_certificate.json').read_text())['counts'],
      'files':{name:{'sha256':sha(ROOT/name),'bytes':(ROOT/name).stat().st_size} for name in ['proof.tex','proof.pdf','proof.txt','check_exact.py','check_results.json','independent_checks.py','independent_certificate.json','check_prior_independent.py','verify.py','build.sh']}}
    (ROOT/'results/verification.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf8')
    print(json.dumps({'status':report['status'],'pdf_pages':8,'checker_pairs':4,'pinned_sources_verified':report['pinned_sources_verified'],'deterministic_pdf_and_text':True},sort_keys=True))

if __name__ == '__main__':
    main()
