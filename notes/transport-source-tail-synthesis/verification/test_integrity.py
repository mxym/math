#!/usr/bin/env python3
"""Integrity self-tests: mutate temporary copies, never the supplied release.

Every positive/negative case is run in fresh normal and -O subprocesses with
identical status/stdout/stderr required. Most semantic failures have the outer
manifest and SHA256SUMS refreshed deliberately, so they exercise the deeper
dependency, protected-mathematics, and archive checks rather than just a stale
outer checksum. The small synthetic fixture has the same 57/10-item contract.
Pass --package ROOT to additionally test actual release copies. No third-party
modules, network access, assert statements, or generated bytecode are used.
The public-builder suite also proves that failures leave every package byte
unchanged, do not emit an external archive, and cannot bless missing mandatory
files even if an adversary has recomputed all manifests. Maintenance is tested
separately and must refuse missing mandatory code or missing acknowledgment.
"""

import argparse
import ast
import copy
import hashlib
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
import tempfile

sys.dont_write_bytecode = True
import verify_integrity as integrity


def check(condition, message):
    if not condition:
        raise RuntimeError(message)


def write_json(path, document):
    path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def record(root, path):
    data = (root / path).read_bytes()
    return {"path": path, "bytes": len(data), "sha256": integrity.sha256(data)}


def reseal_outer(root):
    files, _ = integrity.scan_tree(root)
    records = [record(root, path) for path in sorted(files - integrity.MANIFEST_EXCLUSIONS)]
    write_json(root / "MANIFEST.json", {"schema_version": 1, "files": records})
    records.append(record(root, "MANIFEST.json"))
    (root / "SHA256SUMS").write_text("".join("{}  {}\n".format(item["sha256"], item["path"])
        for item in sorted(records, key=lambda item: item["path"])), encoding="utf-8")


def seal_fixture(root):
    files, _ = integrity.scan_tree(root)
    records = [record(root, path) for path in sorted(files) if integrity.source_eligible(path)]
    document = {"schema_version": 1, "archive": integrity.ARCHIVE_PATH,
                "prefix": integrity.ARCHIVE_PREFIX, "files": records}
    write_json(root / "SOURCE_MANIFEST.json", document)
    archive = root / integrity.ARCHIVE_PATH
    archive.parent.mkdir(exist_ok=True)
    archive.write_bytes(integrity.canonical_gzip_bytes(integrity.canonical_tar_bytes(
        root, {item["path"]: item for item in records}, (root / "SOURCE_MANIFEST.json").read_bytes())))
    reseal_outer(root)


def synthetic_fixture(root):
    root.mkdir()
    (root / "sources").mkdir()
    inputs = []
    for index, local in enumerate(sorted(integrity.REQUIRED_DEPENDENCY_FILES)):
        path = local[len("sources/"):]
        data = "Pinned dependency {}\n".format(index).encode("ascii")
        (root / local).parent.mkdir(parents=True, exist_ok=True)
        (root / "sources" / path).write_bytes(data)
        inputs.append({"path": path, "local_copy": "sources/" + path, "bytes": len(data),
                       "sha256": integrity.sha256(data), "git_blob": integrity.git_blob_sha1(data)})
    write_json(root / "DEPENDENCIES.json", {"inputs": inputs})
    lines = [b"Synthetic integrity fixture.\n", rb"\section{Exact overlap}" + b"\n"]
    types = ["lemma", "proof", "theorem", "proof", "corollary", "proof", "lemma", "proof", "theorem", "proof"]
    for index, kind in enumerate(types):
        lines.append(("\\begin{" + kind + "}\nProtected fixture " + str(index)
                      + ".\n\\end{" + kind + "}\n").encode("ascii"))
    lines.extend([rb"\section{Source-overlap}" + b"\n", b"Unprotected supporting text.\n"])
    source = b"".join(lines)
    (root / "synthesis.tex").write_bytes(source)
    (root / "synthesis.pdf").write_bytes(b"%PDF-1.4\nSynthetic fixture, not a rendered manuscript.\n")
    (root / "README.md").write_text("Self-test fixture.\n", encoding="utf-8")
    (root / "provenance").mkdir()
    section, environments = integrity.extract_protected(source)
    protected = {"source_sha256": integrity.sha256(source),
                 "section_1": {"bytes": len(section), "sha256": integrity.sha256(section)},
                 "environments": [{"index": index, "type": kind, "bytes": len(data),
                                   "sha256": integrity.sha256(data)}
                                  for index, (kind, data) in enumerate(environments, 1)]}
    write_json(root / "provenance/PROTECTED_MATHEMATICS.json", protected)
    for relative in sorted(integrity.REQUIRED_RELEASE_FILES - integrity.GENERATED_FILES):
        path = root / relative
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(("Synthetic required inventory: " + relative + "\n").encode("ascii"))
    seal_fixture(root)


def change_json(root, name, mutation, reseal=False):
    document = read_json(root / name)
    mutation(document)
    write_json(root / name, document)
    if reseal:
        reseal_outer(root)


def mutate_bytes(root, path):
    data = bytearray((root / path).read_bytes())
    check(bool(data), "test mutation requires nonempty input")
    data[-1] ^= 1
    (root / path).write_bytes(data)


def source_change(root):
    data = (root / "synthesis.tex").read_bytes()
    marker = rb"\section{Exact overlap"
    index = data.index(marker) + len(marker)
    (root / "synthesis.tex").write_bytes(data[:index] + b" changed" + data[index:])
    reseal_outer(root)


def environment_change(root):
    data = (root / "synthesis.tex").read_bytes()
    token = next(integrity.ENV_TOKEN.finditer(data))
    index = token.end()
    (root / "synthesis.tex").write_bytes(data[:index] + b" mutation" + data[index:])
    # Refresh only the Section 1 pin, proving that environment pins are checked independently.
    section, _ = integrity.extract_protected((root / "synthesis.tex").read_bytes())
    change_json(root, "provenance/PROTECTED_MATHEMATICS.json", lambda doc: doc.update(
        section_1={"bytes": len(section), "sha256": integrity.sha256(section)}))
    reseal_outer(root)


def source_marker_duplicate(root):
    with (root / "synthesis.tex").open("ab") as stream:
        stream.write(rb"\section{Exact overlap")
    reseal_outer(root)


def dependency_same_size(root):
    path = read_json(root / "DEPENDENCIES.json")["inputs"][0]["local_copy"]
    mutate_bytes(root, path)
    reseal_outer(root)


def dependency_bare_sha1(root):
    document = read_json(root / "DEPENDENCIES.json")
    item = document["inputs"][0]
    item["git_blob"] = hashlib.sha1((root / item["local_copy"]).read_bytes()).hexdigest()
    write_json(root / "DEPENDENCIES.json", document)
    reseal_outer(root)


def replace_symlink(root):
    target = root / "README.md"
    target.unlink()
    target.symlink_to("synthesis.tex")


def rewrite_archive(root, mutation):
    pairs = []
    with tarfile.open(root / integrity.ARCHIVE_PATH, "r:gz") as archive:
        for member in archive:
            stream = archive.extractfile(member)
            check(stream is not None, "fixture archive should contain regular files")
            with stream:
                pairs.append((copy.copy(member), stream.read()))
    mutation(pairs)
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w", format=tarfile.USTAR_FORMAT) as archive:
        for member, data in pairs:
            archive.addfile(member, io.BytesIO(data) if member.isreg() else None)
    (root / integrity.ARCHIVE_PATH).write_bytes(integrity.canonical_gzip_bytes(buffer.getvalue()))
    reseal_outer(root)


def archive_link(pairs):
    pairs[0][0].type = tarfile.SYMTYPE
    pairs[0][0].linkname = "../../escape"
    pairs[0][0].size = 0


def archive_mutation(pairs):
    member, data = pairs[0]
    pairs[0] = (member, bytes([data[0] ^ 1]) + data[1:])


def gzip_metadata(root):
    path = root / integrity.ARCHIVE_PATH
    data = bytearray(path.read_bytes())
    data[4] = 1
    path.write_bytes(data)
    reseal_outer(root)


def gzip_append(root):
    with (root / integrity.ARCHIVE_PATH).open("ab") as stream:
        stream.write(integrity.canonical_gzip_bytes(b""))
    reseal_outer(root)


def gzip_corrupt(root, truncate=False):
    path = root / integrity.ARCHIVE_PATH
    data = bytearray(path.read_bytes())
    if truncate:
        data = data[:-7]
    else:
        data[len(data) // 2] ^= 255
    path.write_bytes(data)
    reseal_outer(root)


def hash_list_append_duplicate(root):
    path = root / "SHA256SUMS"
    text = path.read_text(encoding="utf-8")
    path.write_text(text + text.splitlines()[0] + "\n", encoding="utf-8")


def hash_list_omit_manifest(root):
    path = root / "SHA256SUMS"
    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    path.write_text("".join(line for line in lines if not line.endswith("  MANIFEST.json\n")), encoding="utf-8")


def add_manifest_entry(document, path):
    document["files"].append({"path": path, "bytes": 0, "sha256": "0" * 64})
    document["files"].sort(key=lambda item: item["path"])


