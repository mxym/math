def invoke(verifier, root, optimized, extra=()):
    command = [sys.executable, "-B"]
    if optimized:
        command.append("-O")
    command += [str(verifier), str(root)] + list(extra)
    completed = subprocess.run(command, text=True, capture_output=True, timeout=60, check=False)
    return completed.returncode, completed.stdout, completed.stderr


def snapshot(root):
    result = {}
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root).as_posix()
        if path.is_symlink():
            result[relative] = ("symlink", os.readlink(path))
        elif path.is_dir():
            result[relative] = ("directory",)
        else:
            data = path.read_bytes()
            result[relative] = ("file", len(data), integrity.sha256(data))
    return result


def omit_manifest_record(root, relative):
    change_json(root, "MANIFEST.json", lambda doc: doc.update(
        files=[item for item in doc["files"] if item["path"] != relative]))


def omit_checksum(root, relative):
    path = root / "SHA256SUMS"
    data = path.read_bytes().splitlines(keepends=True)
    suffix = ("  " + relative + "\n").encode("ascii")
    path.write_bytes(b"".join(line for line in data if not line.endswith(suffix)))


def changed_wrapper(root, reseal=False):
    mutate_bytes(root, "verification/run_checks.py")
    if reseal:
        reseal_outer(root)


def missing_resealed(root, relative):
    (root / relative).unlink()
    seal_fixture(root)


def builder_cases():
    result = [
        ("unchanged", lambda root: None, True),
        ("missing-manifest", lambda root: (root / "MANIFEST.json").unlink(), False),
        ("missing-hash-list", lambda root: (root / "SHA256SUMS").unlink(), False),
        ("manifest-omits-wrapper", lambda root: omit_manifest_record(root, "verification/run_checks.py"), False),
        ("manifest-omits-builder", lambda root: omit_manifest_record(root, "verification/package_release.py"), False),
        ("hash-list-omits-wrapper", lambda root: omit_checksum(root, "verification/run_checks.py"), False),
        ("hash-list-omits-manifest", lambda root: omit_checksum(root, "MANIFEST.json"), False),
        ("changed-wrapper", changed_wrapper, False),
        ("changed-wrapper-outer-resealed", lambda root: changed_wrapper(root, True), False),
        ("deleted-wrapper", lambda root: (root / "verification/run_checks.py").unlink(), False),
        ("deleted-builder", lambda root: (root / "verification/package_release.py").unlink(), False),
        ("source-snapshot-changed", lambda root: mutate_bytes(root, sorted(integrity.REQUIRED_DEPENDENCY_FILES)[0]), False),
        ("source-snapshot-outer-resealed", dependency_same_size, False),
    ]
    for relative in ("verification/run_checks.py", "verification/package_release.py",
                     "verification/build_pdf.sh", "verification/verify_integrity.py",
                     "verification/regenerate_manifests.py", "README.md", "BUILD_INFO.json",
                     "RELEASE_DELTA.json", "audit/CORE_PROOF_REVIEW.md",
                     "provenance/RIGHTS_SOURCE_PINS.json", "verification/results/CHECK_REPORT.json"):
        result.append(("missing-all-ledgers-resealed-" + relative,
                       lambda root, relative=relative: missing_resealed(root, relative), False))
    return result


def run_builder_suite(base, label, builder, work):
    count = 0
    for name, mutate, expected_success in builder_cases():
        target = work / "builder-case"
        output = work / "rejected-output.tar.gz"
        shutil.copytree(base, target)
        try:
            mutate(target)
            before = snapshot(target)
            extra = () if expected_success else ("--output", str(output))
            normal = invoke(builder, target, False, extra)
            check(snapshot(target) == before, "{} {}: normal builder changed package bytes".format(label, name))
            optimized = invoke(builder, target, True, extra)
            check(snapshot(target) == before, "{} {}: optimized builder changed package bytes".format(label, name))
            check(normal == optimized, "{} {}: builder normal/-O results differ".format(label, name))
            check((normal[0] == 0) == expected_success,
                  "{} {}: unexpected builder result {!r}".format(label, name, normal))
            if not expected_success:
                check(normal[0] == 1 and normal[2].startswith("FAIL: "),
                      "{} {}: builder rejection is not checked: {!r}".format(label, name, normal))
                check(not output.exists(), "{} {}: rejected builder emitted archive".format(label, name))
            print("PASS: {} / builder-{} (normal and -O; package unchanged)".format(label, name))
            count += 1
        finally:
            shutil.rmtree(target)
            if output.exists():
                output.unlink()
    # Verified external output, no-overwrite, and in-package destination boundary.
    target = work / "builder-output-case"
    shutil.copytree(base, target)
    try:
        before = snapshot(target)
        results = []
        existing_results, inside_results = [], []
        for optimized in (False, True):
            output = work / "verified-output.tar.gz"
            result = invoke(builder, target, optimized, ("--output", str(output)))
            check(result[0] == 0, "external output failed: {!r}".format(result))
            check(output.read_bytes() == (target / integrity.ARCHIVE_PATH).read_bytes(), "external archive differs")
            check(snapshot(target) == before, "external output changed package")
            results.append(result)
            refused = invoke(builder, target, optimized, ("--output", str(output)))
            existing_results.append(refused)
            check(refused[0] == 1, "builder overwrote existing external output")
            check(output.read_bytes() == (target / integrity.ARCHIVE_PATH).read_bytes(), "existing output changed")
            output.unlink()
            refused = invoke(builder, target, optimized, ("--output", str(target / "new-archive.tar.gz")))
            inside_results.append(refused)
            check(refused[0] == 1 and snapshot(target) == before, "builder wrote inside package")
        check(results[0] == results[1], "external output normal/-O results differ")
        check(existing_results[0] == existing_results[1], "existing-output normal/-O results differ")
        check(inside_results[0] == inside_results[1], "in-package-output normal/-O results differ")
        print("PASS: {} / builder-external-output, no-overwrite, and immutable-package (normal and -O)".format(label))
        count += 3
    finally:
        shutil.rmtree(target)
    return count


def run_maintenance_suite(base, label, maintainer, work):
    count = 0
    mutations = [("unchanged", lambda root: None, True)]
    for relative in ("verification/run_checks.py", "verification/package_release.py",
                     "verification/verify_integrity.py", "verification/regenerate_manifests.py",
                     "audit/CORE_PROOF_REVIEW.md", "README.md"):
        mutations.append(("missing-" + relative, lambda root, relative=relative: (root / relative).unlink(), False))
    for name, mutate, expected_success in mutations:
        target = work / "maintenance-case"
        shutil.copytree(base, target)
        try:
            mutate(target)
            before = snapshot(target)
            normal = invoke(maintainer, target, False, ("--acknowledge-no-authenticity",))
            check(snapshot(target) == before, "{} {}: maintenance changed package unexpectedly".format(label, name))
            optimized = invoke(maintainer, target, True, ("--acknowledge-no-authenticity",))
            check(snapshot(target) == before, "{} {}: optimized maintenance changed package unexpectedly".format(label, name))
            check(normal == optimized and (normal[0] == 0) == expected_success,
                  "{} {}: unexpected maintenance result {!r}/{!r}".format(label, name, normal, optimized))
            print("PASS: {} / maintenance-{} (normal and -O; package unchanged)".format(label, name))
            count += 1
        finally:
            shutil.rmtree(target)
    target = work / "maintenance-no-ack"
    shutil.copytree(base, target)
    try:
        before = snapshot(target)
        normal, optimized = invoke(maintainer, target, False), invoke(maintainer, target, True)
        check(normal == optimized and normal[0] == 2 and snapshot(target) == before,
              "maintenance did not require explicit acknowledgment")
        print("PASS: {} / maintenance-requires-acknowledgment (normal and -O; package unchanged)".format(label))
        count += 1
    finally:
        shutil.rmtree(target)
    return count


def run_suite(base, label, verifier, work):
    count = 0
    for name, mutate, expected_success in cases():
        target = work / "case"
        shutil.copytree(base, target)
        try:
            mutate(target)
            normal, optimized = invoke(verifier, target, False), invoke(verifier, target, True)
            check(normal == optimized, "{} {}: normal/-O mismatch: {!r} != {!r}".format(label, name, normal, optimized))
            check((normal[0] == 0) == expected_success,
                  "{} {}: unexpected result {!r}".format(label, name, normal))
            if not expected_success:
                check(normal[0] == 1 and normal[2].startswith("FAIL: "),
                      "{} {}: rejection must be a checked failure, not a crash: {!r}".format(label, name, normal))
            print("PASS: {} / {} (normal and -O)".format(label, name))
            count += 1
        finally:
            shutil.rmtree(target)
    return count


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", type=Path, help="also run the full negative suite on temporary copies of this real release")
    args = parser.parse_args(argv)
    verifier = Path(integrity.__file__).absolute()
    builder = verifier.with_name("package_release.py")
    maintainer = verifier.with_name("regenerate_manifests.py")
    try:
        tree = ast.parse(verifier.read_text(encoding="utf-8"))
        check(not any(isinstance(node, ast.Assert) for node in ast.walk(tree)), "verifier contains assert statements")
        with tempfile.TemporaryDirectory(prefix="transport-integrity-tests-") as temporary:
            work = Path(temporary)
            fixture = work / "fixture"
            synthetic_fixture(fixture)
            count = run_suite(fixture, "synthetic", verifier, work)
            count += run_builder_suite(fixture, "synthetic", builder, work)
            count += run_maintenance_suite(fixture, "synthetic", maintainer, work)
            if args.package is not None:
                package = integrity.checked_root(args.package)
                integrity.verify(package)
                count += run_suite(package, "release", verifier, work)
                count += run_builder_suite(package, "release", builder, work)
                count += run_maintenance_suite(package, "release", maintainer, work)
        print("PASS: {} cases / {} subprocess checks; normal and -O results identical; input releases untouched".format(count, count * 2))
    except (RuntimeError, integrity.IntegrityError, OSError, ValueError, subprocess.SubprocessError) as error:
        print("FAIL: {}".format(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
